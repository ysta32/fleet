// Build-time preparation for @fleet/site. Runs before `next build` and `next dev`.
//  1. Generates app/ink.generated.css: the dark Halyard tokens re-scoped to `.fl-ink`, so the
//     hero and other full-bleed "night" sections stay ink in light mode without copying values.
//  2. Generates lib/optional.generated.ts: the overnight digest fragment and the spend beat figures,
//     only when those packages resolve at build time. Otherwise null.
//  3. Copies the brand mark set from @fleet/ui into public/brand.
//  4. Bundles the hero island (FleetScene + synthetic createDemoFleet) into public/island/
//     unless --gen-only is passed.
import { build } from 'vite';
import react from '@vitejs/plugin-react';
import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { existsSync, realpathSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const site = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repo = path.resolve(site, '../..');
const ui = path.join(repo, 'packages/ui');
const genOnly = process.argv.includes('--gen-only');
const require = createRequire(path.join(site, 'package.json'));

async function inkCss() {
  const tokens = await readFile(path.join(ui, 'tokens.css'), 'utf8');
  const start = tokens.indexOf(":root[data-theme='dark'] {");
  if (start < 0) throw new Error('tokens.css: dark theme block not found');
  const open = tokens.indexOf('{', start);
  const close = tokens.indexOf('\n}', open);
  const body = tokens.slice(open + 1, close);
  const css = `/* GENERATED by scripts/prebuild.mjs from packages/ui/tokens.css. Do not edit. */\n.fl-ink {${body}\n  color-scheme: dark;\n  color: var(--fl-fg);\n}\n`;
  await writeFile(path.join(site, 'app/ink.generated.css'), css);
}

/** Resolvable AND inside this repo: Node's lookup also walks parent directories, which must not leak in. */
function resolves(spec) {
  try {
    const real = realpathSync(require.resolve(spec));
    return real.startsWith(realpathSync(repo) + path.sep);
  } catch {
    return false;
  }
}

async function optionalModules() {
  const lines = [
    '// GENERATED by scripts/prebuild.mjs. Do not edit. Optional sections resolved at build time.',
  ];
  // Overnight digest: packages/digest (workspace) with fixtures/demo-digest.json. Rendered here, at build
  // time, from the package source (bundled for Node by Vite), so the site needs neither the package's dist
  // nor its runtime deps. The fragment and its scoped CSS are inlined as strings.
  const digestDir = path.join(repo, 'packages/digest');
  const htmlSrc = path.join(digestDir, 'src/render/html.ts');
  const fixture = path.join(digestDir, 'fixtures/demo-digest.json');
  let digest = false;
  if (existsSync(htmlSrc) && existsSync(fixture)) {
    const outDir = path.join(site, 'node_modules/.cache/fleet-digest');
    await build({
      configFile: false,
      root: digestDir,
      publicDir: false,
      logLevel: 'warn',
      build: {
        ssr: htmlSrc,
        outDir,
        emptyOutDir: true,
        target: 'node20',
        minify: false,
        rollupOptions: { output: { entryFileNames: 'html.mjs' } },
      },
    });
    const mod = await import(pathToFileURL(path.join(outDir, 'html.mjs')).href + `?t=${Date.now()}`);
    if (typeof mod.renderDigestFragment !== 'function' || typeof mod.DIGEST_CSS !== 'string') {
      throw new Error(
        'packages/digest: renderDigestFragment / DIGEST_CSS not exported from src/render/html.ts',
      );
    }
    const demo = JSON.parse(await readFile(fixture, 'utf8'));
    const html = mod.renderDigestFragment(demo, { timezone: 'UTC' });
    lines.push(`export const digestHtml: string | null = ${JSON.stringify(html)};`);
    lines.push(`export const digestCss: string | null = ${JSON.stringify(mod.DIGEST_CSS)};`);
    digest = true;
  }
  if (!digest)
    lines.push(
      'export const digestHtml: string | null = null;',
      'export const digestCss: string | null = null;',
    );
  // Spend: fleet-spend/web exports <SpendSiteSection /> (no props, built-in example data).
  // The package ships compiled JS (dist/); build it here when the workspace is present but not yet built, so the
  // guard depends on the source being in the repo, not on the order of a deploy's build command.
  const spendDir = path.join(repo, 'packages/spend');
  if (
    existsSync(path.join(spendDir, 'package.json')) &&
    !existsSync(path.join(spendDir, 'dist/web/index.js'))
  ) {
    const name = JSON.parse(await readFile(path.join(spendDir, 'package.json'), 'utf8')).name;
    console.log(`[prebuild] building ${name} (dist missing)`);
    execFileSync('npm', ['run', 'build', '-w', name], { cwd: repo, stdio: 'inherit' });
  }
  // The site shows one spend beat drawn from fleet-spend's own example summary (DEMO_SUMMARY), read here in
  // Node so the page needs no client bundle from the package. Only the figures the beat draws are inlined.
  const hasSpend = resolves('fleet-spend/web');
  await rm(path.join(site, 'lib/spend.generated.tsx'), { force: true });
  if (hasSpend) {
    const mod = await import(pathToFileURL(require.resolve('fleet-spend/web')).href);
    const s = mod.DEMO_SUMMARY;
    if (!s || typeof s.monthToDateUsd !== 'number' || !Array.isArray(s.daily) || !s.budget) {
      throw new Error('fleet-spend/web: DEMO_SUMMARY is missing monthToDateUsd, daily or budget');
    }
    const monthKey = new Date(s.monthStart).toISOString().slice(0, 7);
    const beat = {
      generatedAt: s.generatedAt,
      monthStart: s.monthStart,
      monthToDateUsd: s.monthToDateUsd,
      forecastMonthEndUsd: s.forecastMonthEndUsd,
      budgetUsd: s.budget.monthlyUsd,
      days: s.daily.filter((d) => d.key.startsWith(monthKey)).map((d) => ({ key: d.key, usd: d.costUsd })),
    };
    lines.push(`export const spendBeat: SpendBeat | null = ${JSON.stringify(beat)};`);
  } else {
    lines.push('export const spendBeat: SpendBeat | null = null;');
  }
  lines.push(
    'export interface SpendBeat { generatedAt: number; monthStart: number; monthToDateUsd: number; forecastMonthEndUsd: number; budgetUsd: number | null; days: { key: string; usd: number }[] }',
  );
  await writeFile(path.join(site, 'lib/optional.generated.ts'), lines.join('\n') + '\n');
  console.log(
    `[prebuild] digest section: ${digest ? 'on' : 'off'} · spend section: ${hasSpend ? 'on' : 'off'}`,
  );
}

async function brand() {
  const out = path.join(site, 'public/brand');
  await mkdir(out, { recursive: true });
  for (const f of ['mark.svg', 'wordmark.svg', 'favicon.svg'])
    await copyFile(path.join(ui, 'brand', f), path.join(out, f));
  await copyFile(path.join(ui, 'brand/favicon.svg'), path.join(site, 'public/favicon.svg'));
  const inner = (file) => {
    const m = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(file);
    if (!m) throw new Error('brand svg without <svg> root');
    return m[1].replace(/<title>[^<]*<\/title>/, '');
  };
  const wordmark = inner(await readFile(path.join(ui, 'brand/wordmark.svg'), 'utf8'));
  const mark = inner(await readFile(path.join(ui, 'brand/mark.svg'), 'utf8'));
  await writeFile(
    path.join(site, 'lib/brand.generated.ts'),
    `// GENERATED by scripts/prebuild.mjs from packages/ui/brand. Do not edit.\nexport const WORDMARK_INNER = ${JSON.stringify(wordmark)};\nexport const MARK_INNER = ${JSON.stringify(mark)};\n`,
  );
}

async function island() {
  await build({
    configFile: false,
    root: site,
    publicDir: false,
    logLevel: 'warn',
    plugins: [react()],
    define: { 'process.env.NODE_ENV': '"production"' },
    resolve: { dedupe: ['react', 'react-dom', 'three', '@react-three/fiber'] },
    build: {
      outDir: path.join(site, 'public/island'),
      emptyOutDir: true,
      sourcemap: false,
      minify: 'esbuild',
      target: 'es2020',
      lib: { entry: path.join(site, 'island/entry.tsx'), formats: ['es'], fileName: () => 'fleet-scene.js' },
      rollupOptions: { output: { inlineDynamicImports: true } },
    },
  });
  console.log('[prebuild] island bundled to public/island/fleet-scene.js');
}

await inkCss();
await optionalModules();
await brand();
if (!genOnly) await island();
